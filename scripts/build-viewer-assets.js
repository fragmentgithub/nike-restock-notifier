import { mkdir, readFile, writeFile } from 'node:fs/promises';

// Static Assets routing currently omits ctx.access. Bundle this fixed list as
// text so every request reaches the Worker's verified Access identity check.
// Never enumerate public/: runtime snapshots such as status.json are private data.
const files = [
  ['index.html', 'text/html; charset=utf-8'],
  ['app.js', 'text/javascript; charset=utf-8'],
  ['styles.css', 'text/css; charset=utf-8'],
  ['trend-view.js', 'text/javascript; charset=utf-8'],
  ['restock-trends.js', 'text/javascript; charset=utf-8'],
];
const assets = Object.fromEntries(await Promise.all(files.map(async ([name, contentType]) => [
  `/${name}`,
  { body: await readFile(new URL(`../public/${name}`, import.meta.url), 'utf8'), contentType },
])));
const outputDirectory = new URL('../.viewer-build/', import.meta.url);
await mkdir(outputDirectory, { recursive: true });
await writeFile(new URL('assets.js', outputDirectory),
  `// Generated by scripts/build-viewer-assets.js.\nexport const VIEWER_ASSETS = Object.freeze(${JSON.stringify(assets)});\n`,
  'utf8');

